// Command mldsa-gen regenerates mldsa_testdata.go for the ML-DSA image policy
// tests. It signs the per-platform images of a fixed manifest list with fresh
// ML-DSA-44/65/87 keys and writes the public keys, signature payloads and
// sigstore signatures; the private keys are discarded.
//
// It is a separate module because it needs Go 1.27 (crypto/mldsa) and
// sigstore >= v1.11.0. Run it from this directory:
//
//	go run . > ../mldsa_testdata.go && gofmt -w ../mldsa_testdata.go
package main

import (
	"bytes"
	"crypto/mldsa"
	"crypto/x509"
	"encoding/base64"
	"encoding/json"
	"encoding/pem"
	"fmt"
	"log"
	"os"
	"text/template"

	"github.com/sigstore/sigstore/pkg/signature"
)

const (
	// Manifest list digest of quay.io/openshifttest/busybox-testsigstoresigned,
	// the image used by the existing sigstore tests.
	imageListDigest = "sha256:c5439d7db88ab5423999530349d327b04279ad3161d7596d2126dfb5b02bfd1f"
	// Identity written into the signatures and matched with an
	// ExactRepository signedIdentity, so the signatures don't depend on the
	// test namespace.
	signedIdentity = "example.com/openshift-tests/mldsa-busybox"
)

// CRI-O pulls one platform image out of a manifest list, and containers/image
// verifies the signatures of that image, so every platform OpenShift supports
// is signed. Digests from
// skopeo inspect --raw docker://quay.io/openshifttest/busybox-testsigstoresigned@<imageListDigest>.
var platformDigests = []struct{ Platform, Digest string }{
	{"linux/amd64", "sha256:0415f56ccc05526f2af5a7ae8654baec97d4a614f24736e8eef41a4591f08019"},
	{"linux/arm64", "sha256:bf920ca7f146b802e1c9a8aab1fba3a3fe601c56b075ecef90834c13b90bb5bb"},
	{"linux/ppc64le", "sha256:a1dc9b439291e609fc80847b5c7954e117af4b74b7b60506a07b200e9c08d272"},
	{"linux/s390x", "sha256:16a47375542a993a78368ac80f729382277853523c2baf237c0ae27e41e40fd3"},
}

type signedImage struct {
	Platform, Digest, Payload string
}

type keyData struct {
	Name       string
	PublicKey  string
	Signatures map[string]string
}

func payloadFor(digest string) string {
	payload, err := json.Marshal(map[string]any{
		"critical": map[string]any{
			"type":     "cosign container image signature",
			"image":    map[string]string{"docker-manifest-digest": digest},
			"identity": map[string]string{"docker-reference": signedIdentity},
		},
		"optional": nil,
	})
	if err != nil {
		log.Fatal(err)
	}
	return string(payload)
}

func generate(params mldsa.Parameters, name string, images []signedImage) keyData {
	key, err := mldsa.GenerateKey(params)
	if err != nil {
		log.Fatal(err)
	}
	der, err := x509.MarshalPKIXPublicKey(key.Public())
	if err != nil {
		log.Fatal(err)
	}
	signer, err := signature.LoadMLDSASigner(key)
	if err != nil {
		log.Fatal(err)
	}
	signatures := map[string]string{}
	for _, img := range images {
		sig, err := signer.SignMessage(bytes.NewReader([]byte(img.Payload)))
		if err != nil {
			log.Fatal(err)
		}
		signatures[img.Digest] = base64.StdEncoding.EncodeToString(sig)
	}
	return keyData{
		Name:       name,
		PublicKey:  string(pem.EncodeToMemory(&pem.Block{Type: "PUBLIC KEY", Bytes: der})),
		Signatures: signatures,
	}
}

var out = template.Must(template.New("").Parse(`// Code generated by mldsa-gen; DO NOT EDIT.

package imagepolicy

const (
	mldsaImageListDigest = "{{.ListDigest}}"
	mldsaSignedIdentity  = "{{.Identity}}"
)

// mldsaSignedImages are the per-platform images of the manifest list, with the
// sigstore payload signed for each.
var mldsaSignedImages = []mldsaSignedImage{
{{- range .Images}}
	{
		platform: "{{.Platform}}",
		digest:   "{{.Digest}}",
		payload:  ` + "`{{.Payload}}`" + `,
	},
{{- end}}
}

// mldsaSigners holds a public key per ML-DSA parameter set and its signature
// of each mldsaSignedImages payload, by image digest.
var mldsaSigners = map[string]mldsaSigner{
{{- range .Signers}}
	"{{.Name}}": {
		publicKey: ` + "`{{.PublicKey}}`" + `,
		signatures: map[string]string{
{{- range $digest, $sig := .Signatures}}
			"{{$digest}}": "{{$sig}}",
{{- end}}
		},
	},
{{- end}}
}

// mldsaUntrustedPublicKey is an ML-DSA-65 key that signed nothing.
const mldsaUntrustedPublicKey = ` + "`{{.Untrusted}}`" + `
`))

func main() {
	var images []signedImage
	for _, p := range platformDigests {
		images = append(images, signedImage{Platform: p.Platform, Digest: p.Digest, Payload: payloadFor(p.Digest)})
	}

	signers := []keyData{
		generate(mldsa.MLDSA44(), "ML-DSA-44", images),
		generate(mldsa.MLDSA65(), "ML-DSA-65", images),
		generate(mldsa.MLDSA87(), "ML-DSA-87", images),
	}
	untrusted := generate(mldsa.MLDSA65(), "untrusted", nil)

	if err := out.Execute(os.Stdout, map[string]any{
		"ListDigest": imageListDigest,
		"Identity":   signedIdentity,
		"Images":     images,
		"Signers":    signers,
		"Untrusted":  untrusted.PublicKey,
	}); err != nil {
		log.Fatal(err)
	}
	fmt.Fprintln(os.Stderr, "regenerated ML-DSA test data")
}
